/**
 * माता-पिता का स्वास्थ्य व धन-लाभ — चतुर्थ भाव (माता, सुख-स्वास्थ्य) व नवम भाव (पिता, भाग्य)
 * तथा धन-लाभ हेतु द्वितीय (कुटुंब-धन) व एकादश (लाभ) भाव को भी शामिल किया गया है।
 * ⚠️ यह सामान्य परंपरागत मार्गदर्शन है — किसी चिकित्सीय/वित्तीय गारंटी का दावा नहीं करता।
 * स्वास्थ्य संबंधी किसी भी चिंता हेतु कृपया योग्य चिकित्सक से परामर्श अवश्य लें।
 */
export function parentsHealthWealthInsight(chart) {
  const houses = buildHouses(chart.lagna.rashiIndex, chart.planets);
  const fourth = houses[3]; // माता — सुख व स्वास्थ्य
  const ninth = houses[8]; // पिता — भाग्य व स्थिति
  const second = houses[1]; // कुटुंब-धन
  const eleventh = houses[10]; // आय/लाभ

  const motherHealthScore = scoreHouse(fourth);
  const fatherHealthScore = scoreHouse(ninth);
  const wealthScore = scoreHouse(second).score + scoreHouse(eleventh).score;

  function healthText(score, who, houseNum) {
    const base = HEALTH_NOTE_BY_LORD[score.lord] || '';
    if (score.score >= 1.5) {
      return `${who} का स्वास्थ्य भाव (${houseNum}) शुभ ग्रहों से प्रभावित दिखता है — सामान्यतः स्वास्थ्य ठीक रहने के योग हैं। फिर भी ${base}`;
    }
    if (score.score >= 0) {
      return `${who} का स्वास्थ्य भाव (${houseNum}) मिश्रित प्रभाव में है — नियमित दिनचर्या व समय-समय पर स्वास्थ्य जांच उपयोगी रहेगी। ${base}`;
    }
    return `${who} के स्वास्थ्य भाव (${houseNum}) पर कुछ चुनौतीपूर्ण ग्रहों का प्रभाव दिख रहा है — इसका अर्थ निश्चित बीमारी नहीं, बल्कि अतिरिक्त सावधानी व नियमित जांच की सलाह है। ${base} किसी भी लक्षण हेतु कृपया योग्य चिकित्सक से संपर्क करें।`;
  }

  let wealthLevel, wealthText;
  if (wealthScore >= 1.5) {
    wealthLevel = 'अनुकूल (Favourable)';
    wealthText = 'परिवार के धन-भाव (2रा) व लाभ-भाव (11वां) पर शुभ प्रभाव है — घर में आर्थिक स्थिरता व माता-पिता के लिए धन-लाभ के अच्छे योग बनते हैं।';
  } else if (wealthScore >= 0) {
    wealthLevel = 'सामान्य (Moderate)';
    wealthText = 'धन व लाभ भाव मिश्रित संकेत देते हैं — नियमित बचत व सुनियोजित निवेश से आर्थिक स्थिति धीरे-धीरे मज़बूत होगी।';
  } else {
    wealthLevel = 'प्रयास आवश्यक (Needs effort)';
    wealthText = 'धन-लाभ में बाधाएँ आ सकती हैं — जल्दबाज़ी में बड़े निवेश/उधार से बचें, नीचे दिए उपाय व अनुशासित बचत सहायक रहेंगे।';
  }

  // माता-पिता के लिए धन-लाभ के उपाय — दोनों के राशि-स्वामी (लग्न-भाव स्वामी) आधारित
  const motherRemedy = WEALTH_REMEDY_BY_LORD[motherHealthScore.lord];
  const fatherRemedy = WEALTH_REMEDY_BY_LORD[fatherHealthScore.lord];

  return {
    mother: {
      houseNum: 4,
      houseRashi: fourth.rashi,
      lord: motherHealthScore.lord,
      healthText: healthText(motherHealthScore, 'माता', 4),
      wealthRemedy: motherRemedy,
    },
    father: {
      houseNum: 9,
      houseRashi: ninth.rashi,
      lord: fatherHealthScore.lord,
      healthText: healthText(fatherHealthScore, 'पिता', 9),
      wealthRemedy: fatherRemedy,
    },
    familyWealth: {
      level: wealthLevel,
      text: wealthText,
      secondRashi: second.rashi,
      eleventhRashi: eleventh.rashi,
    },
    generalRemedies: [
      'माता-पिता की ओर से नियमित रूप से पितृ-तर्पण/पूजा-पाठ व वरिष्ठजनों का आशीर्वाद लेना पारिवारिक सुख-समृद्धि हेतु शुभ माना जाता है।',
      'घर के मुख्य द्वार पर स्वास्तिक व नियमित रूप से लक्ष्मी-गणेश पूजन करना घर में धन-आगमन हेतु शुभ माना जाता है।',
      'माता-पिता के नाम से यथाशक्ति दान (अन्न, वस्त्र) करना उनके स्वास्थ्य व दीर्घायु हेतु शुभ माना जाता है।',
    ],
    disclaimer: 'ये उपाय पारंपरिक ज्योतिषीय मान्यताओं पर आधारित सामान्य मार्गदर्शन हैं — किसी गारंटीशुदा चिकित्सीय या वित्तीय परिणाम का दावा नहीं करते। स्वास्थ्य हेतु चिकित्सक व निवेश/धन संबंधी बड़े निर्णयों हेतु योग्य वित्तीय सलाहकार से परामर्श अवश्य लें।',
  };
}

