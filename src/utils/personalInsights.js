const BENEFICS = ['गुरु', 'शुक्र', 'बुध', 'चंद्र'];

function scoreHouse(houseInfo) {
  // भाव स्वामी + भाव में बैठे ग्रह — दोनों के आधार पर शुभ/अशुभ स्कोर
  let score = 0;
  const lord = RASHI_LORDS[houseInfo.rashiIndex];
  score += BENEFICS.includes(lord) ? 1 : -0.5;
  houseInfo.planets.forEach((p) => {
    score += BENEFICS.includes(p) ? 1 : -1;
  });
  return { score, lord };
}

const KENDRA_HOUSES = [1, 4, 7, 10];
const TRIKONA_HOUSES = [1, 5, 9];
const DUSTHANA_HOUSES = [6, 8, 12];

function houseStrengthNote(houseNum) {
  if (TRIKONA_HOUSES.includes(houseNum)) return 'यह स्थिति सामान्यतः शुभ (त्रिकोण भाव) मानी जाती है, जिससे परिणाम अपेक्षाकृत अच्छे मिलने की संभावना रहती है';
  if (KENDRA_HOUSES.includes(houseNum)) return 'यह स्थिति बल देने वाली (केंद्र भाव) मानी जाती है, जिससे इस विषय को स्थिरता व मजबूती मिलती है';
  if (DUSTHANA_HOUSES.includes(houseNum)) return 'यह स्थिति (दुस्थान भाव) कुछ संघर्ष या देरी का संकेत दे सकती है, पर धैर्य व सही प्रयास से परिणाम बेहतर होते जाते हैं';
  return 'यह एक सामान्य/मिश्रित स्थिति मानी जाती है — फल समय के साथ धीरे-धीरे प्रकट होंगे';
}

/**
 * किसी कारक ग्रह (जैसे भाव-स्वामी) की स्वयं की कुंडली में स्थिति (कौन-से भाव व राशि में, वक्री या नहीं)
 * के आधार पर एक अतिरिक्त, चार्ट-विशिष्ट (chart-specific) वाक्य बनाना — ताकि सिर्फ "स्वामी ग्रह" एक जैसा
 * होने पर भी दो अलग कुंडलियों का विश्लेषण एक जैसा न दिखे।
 */
function describeLordPlacement(chart, houses, lordName) {
  const info = chart.planets[lordName];
  if (!info) return null;
  const houseEntry = houses.find((h) => h.rashiIndex === info.rashiIndex);
  const houseNum = houseEntry ? houseEntry.houseNumber : null;
  if (!houseNum) return null;
  const retro = info.isRetrograde ? ', तथा वक्री (Retrograde) अवस्था में है' : '';
  return `${lordName} स्वयं आपकी कुंडली में ${houseNum}वें भाव (${info.rashi} राशि, ${info.nakshatra} नक्षत्र) में स्थित है${retro} — ${houseStrengthNote(houseNum)}।`;
}

