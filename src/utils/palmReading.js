// यह पारंपरिक हस्तरेखा-शास्त्र (Palmistry) पर आधारित एक नियम-आधारित (rule-based)
// कंटेंट-इंजन है। अपलोड/स्कैन की गई हथेली की फोटो से एक "seed" निकाला जाता है
// (इमेज के पिक्सल-पैटर्न पर आधारित), और उस seed के अनुसार परंपरागत हस्तरेखा
// ज्ञान में से प्रत्येक रेखा के लिए एक व्याख्या चुनी जाती है — ठीक वैसे ही
// जैसे बाकी ऐप में जन्म-कुंडली आधारित भविष्यवाणियाँ (Dasha/Insights) दी जाती हैं।
// यह वैज्ञानिक निदान नहीं, पारंपरिक/मनोरंजन उद्देश्य की जानकारी है।

// ---------- 1) इमेज से डिटरमिनिस्टिक seed निकालना ----------

/**
 * दी गई इमेज (File/Blob) को छोटे कैनवस पर बनाकर पिक्सल-डेटा से एक न्यूमेरिक
 * "फिंगरप्रिंट" (कई sub-seed सहित) तैयार करता है। एक ही फोटो पर हमेशा एक जैसा
 * परिणाम आएगा, अलग फोटो पर अलग — इसी से हर बार की रीडिंग विविध महसूस होती है।
 */
export async function deriveSeedFromImage(fileOrBlob) {
  const dataUrl = await readAsDataURL(fileOrBlob);
  const img = await loadImage(dataUrl);

  const size = 48; // छोटे आकार पर सैंपल — तेज़ व पर्याप्त
  const canvas = document.createElement('canvas');
  canvas.width = size;
  canvas.height = size;
  const ctx = canvas.getContext('2d');
  ctx.drawImage(img, 0, 0, size, size);
  const { data } = ctx.getImageData(0, 0, size, size);

  // कई क्षेत्रों (regions) का औसत ब्राइटनेस/रंग निकालकर अलग-अलग sub-seed बनाना,
  // ताकि हर रेखा को स्वतंत्र रूप से एक अलग seed मिले।
  const regions = 8;
  const seeds = new Array(regions).fill(0);
  const cols = 4;
  const rows = 2;
  const cellW = Math.floor(size / cols);
  const cellH = Math.floor(size / rows);

  let globalSum = 0;
  for (let ry = 0; ry < rows; ry++) {
    for (let rx = 0; rx < cols; rx++) {
      const idx = ry * cols + rx;
      let sum = 0;
      let count = 0;
      for (let y = ry * cellH; y < (ry + 1) * cellH; y++) {
        for (let x = rx * cellW; x < (rx + 1) * cellW; x++) {
          const p = (y * size + x) * 4;
          const lum = 0.299 * data[p] + 0.587 * data[p + 1] + 0.114 * data[p + 2];
          sum += lum;
          count++;
        }
      }
      const avg = count ? sum / count : 0;
      seeds[idx] = Math.floor(avg * 997) % 100000;
      globalSum += avg;
    }
  }

  return {
    seeds,
    overallSeed: Math.floor(globalSum * 733) % 100000,
    previewUrl: dataUrl,
  };
}

function readAsDataURL(fileOrBlob) {
  return new Promise((resolve, reject) => {
    const reader = new FileReader();
    reader.onload = () => resolve(reader.result);
    reader.onerror = () => reject(new Error('फोटो पढ़ने में समस्या हुई'));
    reader.readAsDataURL(fileOrBlob);
  });
}

function loadImage(src) {
  return new Promise((resolve, reject) => {
    const img = new window.Image();
    img.onload = () => resolve(img);
    img.onerror = () => reject(new Error('फोटो लोड नहीं हो पाई'));
    img.src = src;
  });
}

function pick(arr, seed) {
  return arr[Math.abs(seed) % arr.length];
}

