export default function BlogPage({ onNavigate, initialPostId }) {
  const [activePost, setActivePost] = useState(initialPostId || null);

  useEffect(() => {
    if (initialPostId) setActivePost(initialPostId);
  }, [initialPostId]);

  if (activePost) {
    const post = BLOG_POSTS.find((p) => p.id === activePost);
    if (!post) setActivePost(null);
    return (
      <div className="hc-page">
        <section className="hc-hero">
          <h1>{post.title}</h1>
          <p>{post.date} · {post.tag}</p>
        </section>
        <div className="app-container" style={{ padding: '24px 0', maxWidth: 760 }}>
          <button type="button" className="btn-link" onClick={() => setActivePost(null)} style={{ marginBottom: 16 }}>
            ← सभी लेख पर वापस जाएँ
          </button>
          <div className="card">
            {post.body.map((para, i) => (
              <p key={i} style={{ lineHeight: 1.8, marginBottom: 16 }}>{para}</p>
            ))}
          </div>
          <div className="card" style={{ marginTop: 20, textAlign: 'center' }}>
            <h3 style={{ marginTop: 0 }}>अपनी कुंडली से जुड़ी जानकारी चाहिए?</h3>
            <button type="button" className="btn-primary" onClick={() => onNavigate('kundli')}>अपनी कुंडली बनाएं</button>
          </div>
        </div>
      </div>
    );
  }

  return (
    <div className="hc-page">
      <section className="hc-hero">
        <h1>🕉️ ज्योतिष ज्ञान — ब्लॉग</h1>
        <p>राशि, ग्रह, कुंडली मिलान व विवाह से जुड़ी उपयोगी जानकारी।</p>
      </section>

      <div className="app-container" style={{ padding: '24px 0' }}>
        <div className="services-grid">
          {BLOG_POSTS.map((p) => (
            <button type="button" key={p.id} className="service-card" style={{ textAlign: 'left' }} onClick={() => setActivePost(p.id)}>
              <span className="service-icon">🕉️</span>
              <h4>{p.title}</h4>
              <p className="muted small" style={{ marginBottom: 6 }}>{p.excerpt}</p>
              <span className="blog-date">{p.date} · {p.tag}</span>
            </button>
          ))}
        </div>
      </div>
    </div>
  );
}
